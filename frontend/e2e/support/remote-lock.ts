import { randomUUID } from "node:crypto";
import type { Page } from "@playwright/test";

/**
 * A remote designer session that holds a server-side node lock.
 *
 * The helper intentionally uses a raw browser WebSocket (in a second browser
 * context) instead of the app's lock-session module: that keeps the simulation
 * independent from the page under test and gives us a unique, explicit session
 * id — exactly what `/ws/designer-lock/{pageId}/` expects.
 */

export interface AcquireRemoteLockOptions {
  pageId: number;
  nodeId: string;
  /** Admin JWT fetched through the REST API. */
  token: string;
  /** Override for deterministic tests; a UUID is generated by default. */
  sessionId?: string;
  timeout?: number;
}

export interface RemoteLock {
  nodeId: string;
  sessionId: string;
  expiresAt: string;
}

/** Acquire `nodeId` from the remote page's origin. Caller must navigate first. */
export async function acquireRemoteLock(
  page: Page,
  options: AcquireRemoteLockOptions
): Promise<RemoteLock> {
  const { pageId, nodeId, token, timeout = 8_000 } = options;
  const sessionId = options.sessionId ?? randomUUID();
  if (!token) throw new Error("acquireRemoteLock requires an admin JWT");

  const result = await page.evaluate(
    async ({ pageId: targetPageId, nodeId: targetNodeId, token: auth, sessionId: sid, timeout: waitMs }) => {
      const socket = new WebSocket(
        `ws://${location.host}/ws/designer-lock/${targetPageId}/?token=${encodeURIComponent(
          auth
        )}&session=${encodeURIComponent(sid)}`
      );

      const received: any[] = [];
      const waiters: {
        predicate: (message: any) => boolean;
        resolve: (message: any) => void;
        reject: (error: Error) => void;
        timer: number;
      }[] = [];

      socket.onmessage = (event: MessageEvent) => {
        let message: any;
        try {
          message = JSON.parse(String(event.data));
        } catch {
          return;
        }
        received.push(message);
        for (let index = waiters.length - 1; index >= 0; index -= 1) {
          const waiter = waiters[index];
          if (!waiter.predicate(message)) continue;
          waiters.splice(index, 1);
          window.clearTimeout(waiter.timer);
          waiter.resolve(message);
        }
      };

      const waitFor = (predicate: (message: any) => boolean): Promise<any> => {
        const existing = received.find(predicate);
        if (existing) return Promise.resolve(existing);
        return new Promise((resolve, reject) => {
          const waiter = {
            predicate,
            resolve,
            reject,
            timer: 0,
          };
          waiter.timer = window.setTimeout(() => {
            const index = waiters.indexOf(waiter);
            if (index >= 0) waiters.splice(index, 1);
            reject(
              new Error(
                `Timed out waiting for lock message; received: ${received
                  .map((item) => item?.type || "?")
                  .join(", ")}`
              )
            );
          }, waitMs);
          waiters.push(waiter);
        });
      };

      await new Promise<void>((resolve, reject) => {
        socket.onopen = () => resolve();
        socket.onerror = () => reject(new Error("designer-lock WebSocket failed to open"));
      });
      await waitFor((message) => message?.type === "snapshot");
      socket.send(
        JSON.stringify({
          type: "acquire",
          nodeId: targetNodeId,
          requestId: `e2e-lock-${Date.now().toString(36)}`,
        })
      );
      const outcome = await waitFor(
        (message) =>
          (message?.type === "lock-granted" && message.nodeId === targetNodeId) ||
          (message?.type === "lock-denied" && message.nodeId === targetNodeId)
      );
      if (outcome.type === "lock-denied") {
        throw new Error(
          `Remote lock was denied for ${targetNodeId}; owner=${
            outcome.owner?.username || outcome.owner?.sessionId || "unknown"
          }`
        );
      }
      (window as any).__wpRemoteLock = { socket, nodeId: targetNodeId, sessionId: sid };
      return {
        expiresAt: String(outcome.expiresAt || ""),
      };
    },
    { pageId, nodeId, token, sessionId, timeout }
  );

  return { nodeId, sessionId, expiresAt: result.expiresAt };
}

/**
 * Explicitly release the simulated remote lock and wait for the server's
 * `lock:release` broadcast, then close the socket. Matching the broadcast (and
 * not only the close event) proves the lock was released while connected.
 */
export async function releaseRemoteLock(page: Page, timeout = 8_000): Promise<void> {
  const released = await page.evaluate(async (waitMs: number) => {
    const handle = (window as any).__wpRemoteLock;
    if (!handle?.socket) return false;
    const socket: WebSocket = handle.socket;
    try {
      await new Promise<void>((resolve, reject) => {
        const timer = window.setTimeout(() => {
          socket.removeEventListener("message", onMessage);
          reject(new Error("Timed out waiting for the remote lock release broadcast"));
        }, waitMs);
        const onMessage = (event: MessageEvent) => {
          let message: any;
          try {
            message = JSON.parse(String(event.data));
          } catch {
            return;
          }
          if (
            message?.type === "lock" &&
            message?.action === "release" &&
            message?.nodeId === handle.nodeId
          ) {
            window.clearTimeout(timer);
            socket.removeEventListener("message", onMessage);
            resolve();
          }
        };
        socket.addEventListener("message", onMessage);
        socket.send(JSON.stringify({ type: "release", nodeId: handle.nodeId }));
      });
    } finally {
      socket.close();
      delete (window as any).__wpRemoteLock;
    }
    return true;
  }, timeout);

  if (!released) throw new Error("No simulated remote lock is currently held");
}

/** Best-effort cleanup; closing the socket also releases its locks server-side. */
export async function closeRemoteLock(page: Page): Promise<void> {
  if (page.isClosed()) return;
  await page.evaluate(() => {
    const handle = (window as any).__wpRemoteLock;
    if (!handle?.socket) return;
    try {
      handle.socket.close();
    } catch {
      /* ignore */
    }
    delete (window as any).__wpRemoteLock;
  });
}
